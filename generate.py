#!/usr/bin/env python3
"""Emit self-contained language modules from the token files.

A surface in another repository cannot import tokens.toml across a checkout
boundary, and frog cannot take a runtime dependency on a sibling directory it may
never see. So the tokens are *compiled* into one dependency-free module per
language, which a surface vendors.

The emitted files carry the source revision in a header. A vendored copy is
therefore traceable to the exact token file it came from, and `--check` proves a
vendor's copy is not stale.

    python3 generate.py            # write generated/{ragbaz_design.py,ragbaz_design.rs}
    python3 generate.py --check    # exit 1 if they are stale; for CI

Deliberately NOT emitted: layout. The frame is a grammar each renderer implements
in its own toolkit (docs/layout.md), because that is the point of keeping the
reconciliation above the renderers.
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import shutil
import subprocess
import tempfile
import sys
import tomllib

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "generated"
TOKEN_FILES = ["tokens.toml", "themes.toml"]


def source_digest() -> str:
    h = hashlib.sha256()
    for name in TOKEN_FILES:
        h.update((HERE / name).read_bytes())
    return h.hexdigest()[:16]


def banner(digest: str, lang: str) -> list[str]:
    mark = "#" if lang == "python" else "//"
    return [
        f"{mark} @generated by design-system/generate.py from tokens.toml + themes.toml",
        f"{mark} source-digest: {digest}   ({lang})",
        f"{mark} DO NOT EDIT. Regenerate in the design system, then vendor the result.",
        f"{mark} The token files are the source of truth; this is a projection of them.",
    ]


def py_literal(value, indent: int = 0) -> str:
    """Deterministic TOML-flavoured literal rendering (stable across runs)."""
    pad = " " * indent
    if isinstance(value, dict):
        if not value:
            return "{}"
        inner = ",\n".join(f"{pad}    {k!r}: {py_literal(v, indent + 4)}"
                           for k, v in sorted(value.items()))
        return "{\n" + inner + f",\n{pad}}}"
    if isinstance(value, list):
        if not value:
            return "[]"
        if all(not isinstance(v, (dict, list)) for v in value):
            return "[" + ", ".join(py_literal(v) for v in value) + "]"
        inner = ",\n".join(f"{pad}    {py_literal(v, indent + 4)}" for v in value)
        return "[\n" + inner + f",\n{pad}]"
    if isinstance(value, bool):
        return "True" if value else "False"
    if value is None:
        return "None"
    return repr(value)


def emit_python(tokens: dict, themes: dict, digest: str) -> str:
    roles = [{"name": r["name"], "kind": r["kind"], "web": r.get("web"),
              "use": r.get("use", "")} for r in tokens["role"]]
    glyphs = {k: dict(v) for k, v in tokens["glyphs"]["set"].items()}
    theme_roles = {name: dict(t.get("role", {})) for name, t in themes["themes"].items()}
    return "\n".join([
        *banner(digest, "python"),
        '"""ragbaz design tokens, generated. See design-system/tokens.toml."""',
        "",
        "from __future__ import annotations",
        "",
        "import os",
        "import re",
        "import sys",
        "",
        f"source_digest = {digest!r}",
        f"ROLES = {py_literal(roles)}",
        f"SPACE_CELLS = {py_literal(tokens['scale']['space']['cells'])}",
        f"THEMES = {py_literal(theme_roles)}",
        f"THEME_DESCRIPTIONS = {py_literal({k: v.get('description', '') for k, v in themes['themes'].items()})}",
        f"COLORLESS_THEMES = {py_literal(sorted(k for k, v in themes['themes'].items() if v.get('color_mode') == 'never'))}",
        f"DEFAULT_THEME = {themes['default_theme']!r}",
        f"GLYPHS = {py_literal(glyphs)}",
        f"GLYPH_POLICY = {py_literal(tokens['glyphs']['policy'])}",
        "",
        "ANSI16 = [",
        '    "#000000", "#cd0000", "#00cd00", "#cdcd00", "#0000ee", "#cd00cd",',
        '    "#00cdcd", "#e5e5e5", "#7f7f7f", "#ff0000", "#00ff00", "#ffff00",',
        '    "#5c5cff", "#ff00ff", "#00ffff", "#ffffff",',
        "]",
        "CUBE = (0, 95, 135, 175, 215, 255)",
        "",
        "",
        "def rgb(colour: str) -> tuple[int, int, int]:",
        '    h = colour.lstrip("#")',
        "    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)",
        "",
        "",
        "def dist(a, b) -> float:",
        '    """Weighted distance: green counts most, matching human sensitivity."""',
        "    r, g, bl = (x - y for x, y in zip(a, b))",
        "    return 2 * r * r + 4 * g * g + 3 * bl * bl",
        "",
        "",
        "def nearest256(colour: str) -> int:",
        "    target = rgb(colour)",
        "    best, best_d = 16, None",
        "    for r in range(6):",
        "        for g in range(6):",
        "            for b in range(6):",
        "                d = dist(target, (CUBE[r], CUBE[g], CUBE[b]))",
        "                if best_d is None or d < best_d:",
        "                    best, best_d = 16 + 36 * r + 6 * g + b, d",
        "    for i in range(24):",
        "        d = dist(target, (8 + 10 * i,) * 3)",
        "        if d < best_d:",
        "            best, best_d = 232 + i, d",
        "    for i, hexv in enumerate(ANSI16):",
        "        d = dist(target, rgb(hexv))",
        "        if d < best_d:",
        "            best, best_d = i, d",
        "    return best",
        "",
        "",
        "def nearest16(colour: str) -> int:",
        "    target = rgb(colour)",
        "    return min(range(16), key=lambda i: dist(target, rgb(ANSI16[i])))",
        "",
        "",
        "def detect_mode() -> str:",
        '    """The best rung this terminal can render."""',
        '    term = os.environ.get("TERM", "")',
        '    if os.environ.get("COLORTERM", "") in ("truecolor", "24bit"):',
        '        return "truecolor"',
        '    if "256" in term:',
        '        return "ansi256"',
        '    return "ansi16" if term else "none"',
        "",
        "",
        "def color_mode(forced: str | None = None, theme: str | None = None) -> str:",
        '    """The off-switch. NO_COLOR off; FORCE_COLOR on and beats NO_COLOR;',
        "    TERM=dumb off; not a TTY off unless forced. A colourless theme wins over",
        '    everything, because it is an explicit request."""',
        "    if theme in COLORLESS_THEMES:",
        '        return "none"',
        "    if forced in (\"truecolor\", \"ansi256\", \"ansi16\", \"none\"):",
        "        return forced",
        '    if forced == "never":',
        '        return "none"',
        '    if forced == "always":',
        "        return detect_mode()",
        "    no_color = os.environ.get(\"NO_COLOR\") is not None",
        "    force = os.environ.get(\"FORCE_COLOR\")",
        "    if no_color and not force:",
        '        return "none"',
        "    if force:",
        "        return detect_mode()",
        '    if os.environ.get("TERM") == "dumb":',
        '        return "none"',
        "    if not sys.stdout.isatty():",
        '        return "none"',
        "    return detect_mode()",
        "",
        "",
        "def glyph_mode() -> str:",
        '    """nerd is opt-in, never detected; then narrow unicode -> ascii."""',
        '    if os.environ.get("RAGBAZ_NERD_FONT"):',
        '        return "nerd"',
        '    enc = (sys.stdout.encoding or "").lower().replace("-", "")',
        '    return "unicode" if enc in ("utf8", "utf16", "utf32") else "ascii"',
        "",
        "",
        "def glyph(key: str) -> str:",
        '    """Resolve a glyph key through the active set."""',
        "    return GLYPHS[key][glyph_mode()]",
        "",
        "",
        "def clip(text: str, width: int) -> str:",
        '    """truncate, but visibly: a clipped value must not look complete."""',
        "    if width <= 0:",
        '        return ""',
        "    if len(text) <= width:",
        "        return text",
        '    mark = GLYPHS["ellipsis"][glyph_mode()]',
        "    return text[:width - len(mark)] + mark if width > len(mark) else text[:width]",
        "",
        "",
        "def visible_len(text: str) -> int:",
        '    """Length ignoring ANSI escapes, for width-aware layout."""',
        '    return len(re.sub(r"\\033\\[[0-9;]*m", "", text))',
        "",
        "",
        "def role(theme: str, name: str) -> str | None:",
        "    return THEMES.get(theme, {}).get(name)",
        "",
    ]) + "\n"


def rs_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit_rust(tokens: dict, themes: dict, digest: str) -> str:
    roles = ", ".join(f'("{r["name"]}", "{r["kind"]}")' for r in tokens["role"])
    cells = ", ".join(str(c) for c in tokens["scale"]["space"]["cells"])
    glyph_keys = sorted(tokens["glyphs"]["set"])
    lines = [
        *banner(digest, "rust"),
        "//! ragbaz design tokens, generated. See design-system/tokens.toml.",
        "",
        "use std::collections::HashMap;",
        "use std::sync::OnceLock;",
        "",
        f'pub const SOURCE_DIGEST: &str = "{digest}";',
        f"pub const DEFAULT_THEME: &str = {rs_str(themes['default_theme'])};",
        "",
        "pub const ROLES: &[(&str, &str)] = &[",
        *([f"    ({rs_str(n)}, {rs_str(k)})," for n, k in
           ((r["name"], r["kind"]) for r in tokens["role"])]),
        "];",
        "",
        f"pub const SPACE_CELLS: [u8; 9] = [{cells}];",
        "",
        "pub const GLYPH_KEYS: &[&str] = &[",
        *[f"    {rs_str(k)}," for k in glyph_keys],
        "];",
        "",
        "#[derive(Clone, Copy, PartialEq, Eq, Debug)]",
        "pub enum Set { Nerd, Unicode, Ascii }",
        "",
        "#[derive(Clone, Copy, PartialEq, Eq, Debug)]",
        "pub enum ColorMode { TrueColor, Ansi256, Ansi16, None }",
        "",
        "impl ColorMode {",
        "    /// NO_COLOR off; FORCE_COLOR on and beats NO_COLOR; TERM=dumb off.",
        "    pub fn detect() -> Self {",
        '        // NO_COLOR is the standard and wins. RAGBAZ_NO_COLOR is honoured as',
        "        // an explicit override so a box can pin it without touching the",
        "        // environment every other tool reads.",
        '        if std::env::var("NO_COLOR").is_ok() || std::env::var("RAGBAZ_NO_COLOR").is_ok() {',
        "            return Self::None;",
        "        }",
        '        if std::env::var("FORCE_COLOR").is_ok() {',
        "            return Self::from_env();",
        "        }",
        '        let term = std::env::var("TERM").unwrap_or_default();',
        '        if term == "dumb" {',
        "            return Self::None;",
        "        }",
        "        Self::from_env()",
        "    }",
        "",
        "    fn from_env() -> Self {",
        '        let term = std::env::var("TERM").unwrap_or_default();',
        '        let colorterm = std::env::var("COLORTERM").unwrap_or_default();',
        '        if colorterm == "truecolor" || colorterm == "24bit" {',
        "            Self::TrueColor",
        '        } else if term.contains("256") {',
        "            Self::Ansi256",
        '        } else if term.is_empty() {',
        "            Self::None",
        "        } else {",
        "            Self::Ansi16",
        "        }",
        "    }",
        "",
        "    pub fn for_terminal(self) -> Self {",
        "        Self::from_env()",
        "    }",
        "}",
        "",
        "impl Set {",
        "    /// nerd is opt-in, never detected; then narrow unicode -> ascii.",
        "    ///",
        "    /// A Rust process cannot ask stdio what encoding it is, so this reads the",
        "    /// locale. If nothing advertises UTF-8, a unicode glyph would be mojibake,",
        "    /// so ASCII is the honest fallback rather than an unreachable variant.",
        "    pub fn detect() -> Self {",
        '        if std::env::var("RAGBAZ_NERD_FONT").is_ok() {',
        "            return Self::Nerd;",
        "        }",
        "        if locale_is_utf8() {",
        "            Self::Unicode",
        "        } else {",
        "            Self::Ascii",
        "        }",
        "    }",
        "}",
        "",
        "/// True when the locale advertises UTF-8 in any of the usual variables.",
        "pub fn locale_is_utf8() -> bool {",
        '    ["LC_ALL", "LC_CTYPE", "LANG"].iter().any(|name| {',
        "        std::env::var(name)",
        '            .map(|v| v.to_ascii_uppercase().contains("UTF"))',
        "            .unwrap_or(false)",
        "    })",
        "}",
        "",
        "const ANSI16: [&str; 16] = [",
        '    "#000000", "#cd0000", "#00cd00", "#cdcd00", "#0000ee", "#cd00cd",',
        '    "#00cdcd", "#e5e5e5", "#7f7f7f", "#ff0000", "#00ff00", "#ffff00",',
        '    "#5c5cff", "#ff00ff", "#00ffff", "#ffffff",',
        "];",
        "const CUBE: [u8; 6] = [0, 95, 135, 175, 215, 255];",
        "",
        "fn rgb(colour: &str) -> (i32, i32, i32) {",
        '    let h = colour.trim_start_matches(\'#\');',
        "    let p = |i: usize| i32::from_str_radix(&h[i..i + 2], 16).unwrap_or(0);",
        "    (p(0), p(2), p(4))",
        "}",
        "",
        "fn dist(a: (i32, i32, i32), b: (i32, i32, i32)) -> i32 {",
        "    let (r, g, bl) = (a.0 - b.0, a.1 - b.1, a.2 - b.2);",
        "    2 * r * r + 4 * g * g + 3 * bl * bl",
        "}",
        "",
        "pub fn nearest256(colour: &str) -> u8 {",
        "    let t = rgb(colour);",
        "    let (mut best, mut bd) = (16u8, i32::MAX);",
        "    for r in 0..6 {",
        "        for g in 0..6 {",
        "            for b in 0..6 {",
        "                let d = dist(t, (CUBE[r] as i32, CUBE[g] as i32, CUBE[b] as i32));",
        "                if d < bd {",
        "                    bd = d;",
        "                    let idx: u16 = 16 + 36 * r as u16 + 6 * g as u16 + b as u16;",
        "                    best = idx as u8;",
        "                }",
        "            }",
        "        }",
        "    }",
        "    for i in 0..24i32 {",
        "        let v = 8 + 10 * i;",
        "        if dist(t, (v, v, v)) < bd {",
        "            bd = dist(t, (v, v, v));",
        "            best = 232 + i as u8;",
        "        }",
        "    }",
        "    for (i, h) in ANSI16.iter().enumerate() {",
        "        let d = dist(t, rgb(h));",
        "        if d < bd {",
        "            bd = d;",
        "            best = i as u8;",
        "        }",
        "    }",
        "    best",
        "}",
        "",
        "pub fn nearest16(colour: &str) -> u8 {",
        "    let t = rgb(colour);",
        "    let mut best = 0u8;",
        "    let mut bd = i32::MAX;",
        "    for (i, h) in ANSI16.iter().enumerate() {",
        "        let d = dist(t, rgb(h));",
        "        if d < bd {",
        "            bd = d;",
        "            best = i as u8;",
        "        }",
        "    }",
        "    best",
        "}",
        "",
    ]
    # themes
    lines.append("/// theme -> role -> hex")
    lines.append("pub fn themes() -> &'static HashMap<&'static str, HashMap<&'static str, &'static str>> {")
    lines.append("    static MAP: OnceLock<HashMap<&'static str, HashMap<&'static str, &'static str>>> = OnceLock::new();")
    lines.append("    MAP.get_or_init(|| {")
    lines.append("        let mut out: HashMap<&'static str, HashMap<&'static str, &'static str>> = HashMap::new();")
    for name, t in sorted(themes["themes"].items()):
        # a colourless theme declares no roles, and `mut` on an empty map is a warning
        has_roles = bool(t.get("role"))
        lines.append("        let mut m = HashMap::new();" if has_roles
                     else "        let m = HashMap::new();")
        for role_name, value in sorted(t.get("role", {}).items()):
            lines.append(f"        m.insert({rs_str(role_name)}, {rs_str(value)});")
        lines.append(f"        out.insert({rs_str(name)}, m);")
    lines.append("        out")
    lines.append("    })")
    lines.append("}")
    lines.append("")
    lines.append("pub fn colorless_themes() -> &'static [&'static str] {")
    colorless = sorted(k for k, v in themes["themes"].items() if v.get("color_mode") == "never")
    lines.append(f"    &[{', '.join(rs_str(c) for c in colorless)}]")
    lines.append("}")
    lines.append("")
    # glyphs
    lines.append("/// glyph key -> (nerd, unicode, ascii)")
    lines.append("pub fn glyphs() -> &'static HashMap<&'static str, (&'static str, &'static str, &'static str)> {")
    lines.append("    static MAP: OnceLock<HashMap<&'static str, (&'static str, &'static str, &'static str)>> = OnceLock::new();")
    lines.append("    MAP.get_or_init(|| {")
    lines.append("        let mut out = HashMap::new();")
    for k in glyph_keys:
        v = tokens["glyphs"]["set"][k]
        lines.append(f"        out.insert({rs_str(k)}, ({rs_str(v['nerd'])}, {rs_str(v['unicode'])}, {rs_str(v['ascii'])}));")
    lines.append("        out")
    lines.append("    })")
    lines.append("}")
    lines.append("")
    lines.append("/// Resolve a glyph key through the active set.")
    lines.append("pub fn glyph(key: &str, set: Set) -> &'static str {")
    lines.append("    let (n, u, a) = match glyphs().get(key) {")
    lines.append("        Some(v) => *v,")
    lines.append("        None => return \"?\",")
    lines.append("    };")
    lines.append("    match set {")
    lines.append("        Set::Nerd => n,")
    lines.append("        Set::Unicode => u,")
    lines.append("        Set::Ascii => a,")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the generated files are stale")
    args = ap.parse_args()

    tokens = tomllib.loads((HERE / "tokens.toml").read_text())
    themes = tomllib.loads((HERE / "themes.toml").read_text())
    digest = source_digest()

    OUT.mkdir(exist_ok=True)
    targets = {
        OUT / "ragbaz_design.py": emit_python(tokens, themes, digest),
        OUT / "ragbaz_design.rs": emit_rust(tokens, themes, digest),
    }

    # An adopting repo runs `cargo fmt --all --check` over the vendored file, and
    # rustfmt.toml's `ignore` is nightly-only, so the emitted file must already be
    # formatted. Hand it to rustfmt rather than hand-formatting it, and do the
    # same in --check so the comparison is against what would actually be written.
    rs_final = format_rust(targets[OUT / "ragbaz_design.rs"])
    targets[OUT / "ragbaz_design.rs"] = rs_final

    stale = []
    for path, content in targets.items():
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        stale.append(path.name)
        if not args.check:
            path.write_text(content)

    if args.check:
        if stale:
            print(f"stale: {', '.join(stale)} - run python3 generate.py", file=sys.stderr)
            return 1
        print(f"generated files are current (source-digest {digest})")
        return 0

    for path in targets:
        print(f"{path.relative_to(HERE)}  {path.stat().st_size} bytes")
    print(f"source-digest {digest}")
    return 0


def format_rust(content: str) -> str:
    """rustfmt the emitted Rust in a temp file and return the formatted text."""
    if not shutil.which("rustfmt"):
        print("warning: rustfmt not found; the emitted Rust may fail `cargo fmt --check`",
              file=sys.stderr)
        return content
    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = pathlib.Path(tmp) / "ragbaz_design.rs"
        tmp_path.write_text(content)
        done = subprocess.run(["rustfmt", "--edition", "2021", str(tmp_path)],
                              capture_output=True, text=True)
        if done.returncode != 0:
            print(f"warning: rustfmt failed ({done.stderr.strip()[:200]}); "
                  "emitting unformatted", file=sys.stderr)
            return content
        return tmp_path.read_text()


if __name__ == "__main__":
    raise SystemExit(main())